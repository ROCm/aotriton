# Data files: <iface>[.<backend>].perfdb
# ---------------------------------------------------------------------------

def file_name(iface: str, backend: str | None) -> str:
    if backend is None:
        return f'{iface}{EXT}'
    if not BACKEND_RE.match(backend):
        raise PerfdbError(f'backend name {backend!r} is not [a-z0-9_]+')
    return f'{iface}.{backend}{EXT}'


def parse_file_name(name: str) -> tuple[str, str | None]:
    """(iface, backend) of a data file name; backend None when unforced."""
    if not name.endswith(EXT):
        raise PerfdbError(f'{name}: not a {EXT} file')
    stem = name[:-len(EXT)]
    iface, _, backend = stem.partition('.')
    return iface, (backend or None)


def canonical_line(line):
    """A results line's value part: NO_DATA, EXCLUDED or the six statistics,
    as canonical text."""
    if line in (NO_DATA, EXCLUDED):
        return line
    values = tuple(line)
    if len(values) != len(STAT_COLUMNS):
        raise PerfdbError(f'a results line has {len(STAT_COLUMNS)} values, got {values}')
    return tuple(fmt4(v) for v in values)


@dataclass
class PerfdbFile:
    """One data file: one iface and backend on one arch of one tag, a block of
    lines per variant ({entry ordinal: line})."""
    iface: str
    backend: str | None
    metadata: dict = field(default_factory=dict)
    blocks: dict = field(default_factory=dict)

    @property
    def name(self) -> str:
        return file_name(self.iface, self.backend)

    def measurement_keys(self) -> dict:
        return {k: self.metadata.get(k) for k in MEASUREMENT_KEYS}

    def set_measurement_keys(self, keys: dict, where: str = '') -> None:
        """Record how the times were taken; a file never mixes methods."""
        for k, v in keys.items():
            if v is None:
                continue
            v = str(v)
            old = self.metadata.get(k)
            if old is not None and old != v:
                raise PerfdbError(f'{where or self.name}: {k} {v!r} differs from the file\'s {old!r}; '
                                  'a file never mixes measurement methods')
            self.metadata[k] = v

    def merge(self, variant: str, lines: dict) -> int:
        """Replace the lines of `variant` given in `lines`; keep the others.
        Returns how many lines changed."""
        block = self.blocks.setdefault(variant, {})
        changed = 0
        for entry, line in lines.items():
            line = canonical_line(line)
            if block.get(int(entry)) != line:
                block[int(entry)] = line
                changed += 1
        return changed


def new_file(iface: str, backend: str | None) -> PerfdbFile:
    metadata = {'iface': iface, 'backend': backend or UNFORCED}
    return PerfdbFile(iface=iface,
                      backend=backend,
                      metadata=metadata)


def read_perfdb(path: Path) -> PerfdbFile:
    path = Path(path)
    iface, backend = parse_file_name(path.name)
    sections = read_sections(path)
    if None in sections:
        raise PerfdbError(f'{path}: lines before the first section')
    metadata = {}
    for fields_ in sections.get(METADATA, []):
        if len(fields_) != 2:
            raise PerfdbError(f'{path}: metadata line {",".join(fields_)} is not key,value')
        metadata[fields_[0]] = fields_[1]
    if metadata.get('iface') != iface or metadata.get('backend') != (backend or UNFORCED):
        raise PerfdbError(f'{path}: metadata iface/backend {metadata.get("iface")}/{metadata.get("backend")} '
                          f'disagree with the file name')
    out = PerfdbFile(iface=iface, backend=backend, metadata=metadata)
    for name, lines in sections.items():
        if name == METADATA:
            continue
        head, _, variant = name.partition(' ')
        if head != RESULTS or not variant.strip():
            raise PerfdbError(f'{path}: unknown section {name!r}')
        variant = variant.strip()
        if not lines or tuple(lines[0]) != RESULTS_HEADER:
            raise PerfdbError(f'{path}: section {name!r} must start with {",".join(RESULTS_HEADER)}')
        block = {}
        for fields_ in lines[1:]:
            entry = int(fields_[0])
            values = fields_[1:]
            if entry in block:
                raise PerfdbError(f'{path}: entry {entry} appears twice in {name!r}')
            if len(values) == 1 and values[0] in (NO_DATA, EXCLUDED):
                block[entry] = values[0]
            else:
                try:
                    block[entry] = canonical_line([float(v) for v in values])
                except ValueError as e:
                    raise PerfdbError(f'{path}: bad line for entry {entry}: {",".join(fields_)}') from e
        out.blocks[variant] = block
    return out


def perfdb_text(f: PerfdbFile) -> str:
    """The canonical text of a data file: metadata in fixed key order,
    variant blocks sorted by name, lines sorted by entry."""
    out = [SHEBANG, f'#! {METADATA}']
    keys = [k for k in METADATA_KEYS if k in f.metadata] + sorted(k for k in f.metadata if k not in METADATA_KEYS)
    out += [f'{k},{f.metadata[k]}' for k in keys]
    for variant in sorted(f.blocks):
        block = f.blocks[variant]
        if not block:
            continue
        out.append(f'#! {RESULTS} {variant}')
        out.append(','.join(RESULTS_HEADER))
        for entry in sorted(block):
            line = block[entry]
            out.append(f'{entry},{line}' if isinstance(line, str) else f'{entry},{",".join(line)}')
    return '\n'.join(out) + '\n'


def write_perfdb(path: Path, f: PerfdbFile) -> bool:
    return write_if_changed(Path(path), perfdb_text(f))


def load_arch(root: Path, tag: str, arch: str) -> dict[str, PerfdbFile]:
    d = data_dir(root, tag, arch)
    if not d.is_dir():
        return {}
    return {p.name: read_perfdb(p) for p in sorted(d.glob(f'*{EXT}'))}


def numeric(line) -> tuple | None:
    """The statistics of a line as floats, or None for a marker or no line."""
    if line is None or isinstance(line, str):
        return None
    return tuple(float(v) for v in line)


def median(line) -> float | None:
    values = numeric(line)
    return values[0] if values else None


# ---------------------------------------------------------------------------
# platform.csv
# ---------------------------------------------------------------------------

def read_platform(path: Path) -> list[dict]:
    if not path.is_file():
        return []
    header, rows = _read_csv(path)
    if header != PLATFORM_COLUMNS:
        raise PerfdbError(f'{path}: columns {header}, expected {PLATFORM_COLUMNS}')
    return [dict(zip(header, r)) for r in rows]


def merge_platform(rows: list[dict], configs) -> list[dict]:
    """Merge `configs`, ((configuration dict without `measured`), date) pairs,
    into platform rows: one row per distinct configuration, `measured`
    spanning its first and last date ('YYYY-MM-DD..YYYY-MM-DD')."""
    keyed: dict[tuple, list[str]] = {}
    for row in rows:
        key = tuple(row.get(c, '') for c in PLATFORM_COLUMNS[:-1])
        first, _, last = row.get('measured', '').partition('..')
        keyed[key] = [first, last or first]
    for config, day in configs:
        key = tuple('' if config.get(c) is None else str(config.get(c)) for c in PLATFORM_COLUMNS[:-1])
        span = keyed.setdefault(key, [day, day])
        span[0] = min(span[0], day) if span[0] else day
        span[1] = max(span[1], day)
    out = []
    for key in sorted(keyed):
        first, last = keyed[key]
        out.append({**dict(zip(PLATFORM_COLUMNS[:-1], key)),
                    'measured': first if first == last else f'{first}..{last}'})
    return out


def platform_text(rows: list[dict]) -> str:
    return _csv_text(PLATFORM_COLUMNS, [tuple(r[c] for c in PLATFORM_COLUMNS) for r in rows])


def platform_conflicts(rows: list[dict]) -> dict[str, list[tuple]]:
    """Variants whose machines report different device ids or default power
    caps: {variant: [(gpu_device_id, power_cap_default_w), ...]}."""
    seen: dict[str, set] = {}
    for r in rows:
        seen.setdefault(r['variant'], set()).add((r['gpu_device_id'], r['power_cap_default_w']))
    return {v: sorted(s) for v, s in seen.items() if len(s) > 1}


# ---------------------------------------------------------------------------
# Rendering
# ---------------------------------------------------------------------------

def _cell(line, tflops=None) -> str:
    if line is None:
        return ''
    if line == EXCLUDED:
        return SHOW_EXCLUDED
    if line == NO_DATA:
        return SHOW_NO_DATA
    return fmt4(tflops) if tflops is not None else fmt4(median(line))


def _signed(x: float) -> str:
    return ('+' if x >= 0 else '-') + fmt4(abs(x))


def _table(header, rows) -> list[str]:
    out = ['| ' + ' | '.join(str(h) for h in header) + ' |',
           '|' + '|'.join('---' for _ in header) + '|']
    out += ['| ' + ' | '.join(str(c) for c in row) + ' |' for row in rows]
    return out


class _ArchView:
    """One (tag, arch): its files, and lookups by entry."""

    def __init__(self, root: Path, tag: str, arch: str, desc, entries: EntryList):
        self.root, self.tag, self.arch, self.desc, self.entries = root, tag, arch, desc, entries
        self.files = load_arch(root, tag, arch)
        self.platform = read_platform(data_dir(root, tag, arch) / PLATFORM_CSV)

    def variants(self) -> list[str]:
        return sorted({v for f in self.files.values() for v, b in f.blocks.items() if b})

    def backends(self, iface: str) -> list[str]:
        return sorted(f.backend for f in self.files.values() if f.iface == iface and f.backend is not None)

    def line(self, iface, backend, variant, entry):
        if entry is None:
            return None
        f = self.files.get(file_name(iface, backend))
        if f is None:
            return None
        ordinal = self.entries.ordinal_of(self.desc, entry)
        return None if ordinal is None else f.blocks.get(variant, {}).get(ordinal)

    def tflops_cell(self, iface, backend, variant, entry) -> tuple[str, float | None]:
        line = self.line(iface, backend, variant, entry)
        m = median(line)
        if m is None:
            return _cell(line), None
        t = self.desc.tflops(iface, entry, m)
        return fmt4(t), t


def _prime_lines(view: _ArchView, iface: str, backend, variant: str) -> list[str]:
    out = []
    for table in view.desc.prime_tables(iface):
        out += ['', f'#### {table.title}', '']
        rows = []
        for row_value, cells in table.rows:
            texts = []
            for main_entry, alt_entry in cells:
                main_text, main_t = view.tflops_cell(iface, backend, variant, main_entry)
                alt_text, alt_t = view.tflops_cell(iface, backend, variant, alt_entry)
                if main_t is not None and alt_t is not None:
                    texts.append(f'{main_text} ({_signed(alt_t - main_t)})')
                elif main_t is None and alt_t is not None:
                    texts.append(f'{main_text} ({table.alt_label} {alt_text})'.strip())
                else:
                    texts.append(main_text)
            rows.append([row_value] + texts)
        header = [f'{table.row_label} \\ {table.column_label}'] + list(table.columns)
        out += _table(header, rows)
    return out


def _llm_lines(view: _ArchView, iface: str, variant: str) -> list[str]:
    cases = [c for c in view.desc.llm_cases()
             if not c.pending and iface in view.desc.phase_ifaces(c.phase)]
    if not cases:
        return []
    backends = view.backends(iface)
    columns = list(view.desc.case_columns(cases[0].entry))
    rows = []
    for case in cases:
        described = view.desc.case_columns(case.entry)
        cells = [view.tflops_cell(iface, None, variant, case.entry)[0]]
        cells += [view.tflops_cell(iface, b, variant, case.entry)[0] for b in backends]
        rows.append([case.model] + [described[c] for c in columns] + cells)
    return ['', f'#### {iface}', ''] + _table(['model'] + columns + ['operator'] + backends, rows)


def _platform_lines(view: _ArchView, variant: str) -> list[str]:
    rows = [r for r in view.platform if r['variant'] == variant]
    if not rows:
        return ['No platform recorded.']
    out = []
    for r in rows[:4] if len(rows) > 5 else rows:
        gpu = f"device {r['gpu_device_id'] or '?'}, {r['vram_gib'] or '?'} GiB"
        if r['power_cap_w'] or r['power_cap_default_w']:
            gpu += f", power cap {r['power_cap_w'] or '?'} W (default {r['power_cap_default_w'] or '?'} W)"
        host = ', '.join(x for x in (r['cpu'], r['ram_speed'] and f"RAM {r['ram_speed']}", r['os'],
                                     r['kernel'] and f"kernel {r['kernel']}",
                                     r['amdgpu'] and f"amdgpu {r['amdgpu']}") if x)
        out.append(f"- {gpu}, {r['gpus_per_node'] or '?'} GPUs per node, thermal gate "
                   f"{r['thermal_gate'] or '?'}; {host}; ROCm {r['rocm'] or '?'}; "
                   f"measured {r['measured']}")
    if len(rows) > 5:
        out.append(f'- and {len(rows) - 4} more configurations, see `{DATA}/{view.arch}/{PLATFORM_CSV}`')
    return out


def render_arch(view: _ArchView) -> str:
    desc = view.desc
    out = [GENERATED, '', f'# AOTriton {view.tag} on {view.arch}', '',
           'Matrix-core TFLOPS from the median time; only the two matmuls count, so dropout shows '
           'as lower TFLOPS. Prime cells give the bf16 TFLOPS of the unforced operator, and the fp16 '
           'difference in parentheses. '
           f'`{SHOW_EXCLUDED}`: excluded (not supported, or does not fit the GPU). '
           f'`{SHOW_NO_DATA}`: measured, no data. Blank: not measured.', '',
           'The unforced operator is what users get, measured as it is: it can be slower than its '
           'fastest forced backend, because the operator database\'s choice is not corrected.']
    for variant in view.variants():
        out += ['', f'## Variant `{variant}`', ''] + _platform_lines(view, variant)
        for iface in desc.ifaces():
            out += ['', f'### {iface}: prime']
            out += _prime_lines(view, iface, None, variant)
        llm = []
        for iface in desc.ifaces():
            llm += _llm_lines(view, iface, variant)
        if llm:
            out += ['', '### LLM cases'] + llm
        for iface in desc.ifaces():
            for backend in view.backends(iface):
                out += ['', '<details>', f'<summary>{iface} forced to {backend}: prime</summary>']
                out += _prime_lines(view, iface, backend, variant)
                out += ['', '</details>']
    return '\n'.join(out) + '\n'


def compare_files(old: dict[str, PerfdbFile], new: dict[str, PerfdbFile], *, variant: str | None = None,
                  names=None):
    """Join two tags' files of one arch: by file name, then variant, then
    entry. Returns (ratios, refused): ratios is a list of (file name, variant,
    entry, old median, new median, old/new); refused lists the file names
    whose measurement keys differ."""
    ratios, refused = [], []
    for name in sorted(set(old) & set(new)):
        if names is not None and name not in names:
            continue
        a, b = old[name], new[name]
        if a.measurement_keys() != b.measurement_keys():
            refused.append(name)
            continue
        for v in sorted(set(a.blocks) & set(b.blocks)):
            if variant is not None and v != variant:
                continue
            for entry in sorted(set(a.blocks[v]) & set(b.blocks[v])):
                ma, mb = median(a.blocks[v][entry]), median(b.blocks[v][entry])
                if ma is not None and mb is not None and ma > 0 and mb > 0:
                    ratios.append((name, v, entry, ma, mb, ma / mb))
    return ratios, refused


def _previous_tag(root: Path, tags: list[str], tag: str, arch: str) -> str | None:
    earlier = [t for t in tags if tag_sort_key(t) < tag_sort_key(tag) and data_dir(root, t, arch).is_dir()]
    return earlier[-1] if earlier else None


def _llm_ordinals(desc, entries: EntryList) -> set[int]:
    out = set()
    for case in desc.llm_cases():
        ordinal = entries.ordinal_of(desc, case.entry)
        if ordinal is not None:
            out.add(ordinal)
    return out


def _view(views: dict, root, tag, arch, desc, entries) -> _ArchView:
    """The (tag, arch) view, loaded once per `views` (one dict per render run)."""
    key = (tag, arch)
    if key not in views:
        views[key] = _ArchView(root, tag, arch, desc, entries)
    return views[key]


def _summary(root, desc, entries, tags, tag, arch, variant, views: dict):
    """(previous tag, {iface: geomean}, LLM geomean, per-case rows) of one
    (tag, arch, variant) against the previous tag with that arch. `views`
    memoizes the loaded data of the render run."""
    prev = _previous_tag(root, tags, tag, arch)
    if prev is None:
        return None, {}, None, []
    old = _view(views, root, prev, arch, desc, entries).files
    new = _view(views, root, tag, arch, desc, entries).files
    unforced = {file_name(i, None) for i in desc.ifaces()}
    ratios, _ = compare_files(old, new, variant=variant, names=unforced)
    per_iface = {}
    for iface in desc.ifaces():
        per_iface[iface] = geomean(r[5] for r in ratios if r[0] == file_name(iface, None))
    llm = _llm_ordinals(desc, entries)
    llm_mean = geomean(r[5] for r in ratios if r[2] in llm)
    cases = []
    by_key = {(r[0], r[2]): r for r in ratios}
    for case in desc.llm_cases():
        ordinal = entries.ordinal_of(desc, case.entry)
        for iface in desc.phase_ifaces(case.phase):
            r = by_key.get((file_name(iface, None), ordinal))
            if r is not None:
                cases.append((case, iface, r[3], r[4], r[5]))
    return prev, per_iface, llm_mean, cases


def _ratio_text(x) -> str:
    return '' if x is None else fmt4(x)


def render_tag(root: Path, desc, entries: EntryList, tags: list[str], tag: str,
               views: dict | None = None) -> str:
    views = {} if views is None else views
    out = [GENERATED, '', f'# AOTriton {tag}', '',
           'Ratios are geometric means of old over new median time of the unforced operator, against '
           'the previous tag measured on the same arch and variant: above 1 is faster.', '']
    header = ['arch', 'variant', 'previous'] + list(desc.ifaces()) + ['LLM cases']
    rows, case_lines = [], []
    for arch in list_arches(root, tag):
        view = _view(views, root, tag, arch, desc, entries)
        for variant in view.variants():
            prev, per_iface, llm_mean, cases = _summary(root, desc, entries, tags, tag, arch, variant, views)
            rows.append([f'[{arch}]({arch}.md)', variant, prev or '']
                        + [_ratio_text(per_iface.get(i)) for i in desc.ifaces()] + [_ratio_text(llm_mean)])
            if cases:
                case_lines += ['', f'### {arch}, variant `{variant}`, against {prev}', '']
                columns = list(desc.case_columns(cases[0][0].entry))
                case_rows = []
                for case, iface, old_m, new_m, ratio in cases:
                    described = desc.case_columns(case.entry)
                    case_rows.append([case.model] + [described[c] for c in columns]
                                     + [iface, fmt4(old_m), fmt4(new_m), fmt4(ratio)])
                case_lines += _table(['model'] + columns + ['iface', 'old µs', 'new µs', 'old/new'], case_rows)
    out += _table(header, rows)
    if case_lines:
        out += ['', '## LLM cases'] + case_lines
    return '\n'.join(out) + '\n'


def render_index(root: Path, desc, entries: EntryList, tags: list[str], views: dict | None = None) -> str:
    views = {} if views is None else views
    out = [GENERATED, '', '# Performance database', '',
           'End-to-end performance of AOTriton\'s public APIs, one directory per release tag. '
           'Format: docs/Human Readable Performance Database Format.md.', '',
           '## Tags', '']
    out += [f'- [{t}]({t}/README.md)' for t in tags] or ['No tag yet.']
    arches = sorted({a for t in tags for a in list_arches(root, t)})
    for arch in arches:
        out += ['', f'## {arch}', '',
                'Geometric mean of old over new median time against the previous tag; above 1 is faster.', '']
        rows = []
        for tag in tags:
            if not data_dir(root, tag, arch).is_dir():
                continue
            view = _view(views, root, tag, arch, desc, entries)
            for variant in view.variants():
                prev, per_iface, llm_mean, _ = _summary(root, desc, entries, tags, tag, arch, variant, views)
                rows.append([f'[{tag}]({tag}/{arch}.md)', variant, prev or '']
                            + [_ratio_text(per_iface.get(i)) for i in desc.ifaces()] + [_ratio_text(llm_mean)])
        out += _table(['tag', 'variant', 'previous'] + list(desc.ifaces()) + ['LLM cases'], rows)
    return '\n'.join(out) + '\n'


def render_all(root: Path, desc) -> dict[Path, str]:
    """Every generated markdown file of the tree, {path: text}."""
    root = Path(root)
    entries = EntryList.load(root, desc.PROBLEM_COLUMNS, desc.SIZE_COLUMNS)
    tags = list_tags(root)
    views: dict = {}        # (tag, arch) -> _ArchView, each loaded once for the whole run
    out = {root / README: render_index(root, desc, entries, tags, views)}
    for tag in tags:
        out[root / tag / README] = render_tag(root, desc, entries, tags, tag, views)
        for arch in list_arches(root, tag):
            out[root / tag / f'{arch}.md'] = render_arch(_view(views, root, tag, arch, desc, entries))
    return out


def render(root: Path, desc, *, check: bool = False) -> list[Path]:
    """Write every generated markdown file, or with `check` only compare.
    Returns the files that differed."""
    differ = []
    for path, text in render_all(root, desc).items():
        current = path.read_text(encoding='utf-8') if path.is_file() else None
        if current != text:
            differ.append(path)
            if not check:
                path.write_text(text, encoding='utf-8')
    return differ


