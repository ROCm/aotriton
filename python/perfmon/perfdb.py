def _desc_for(root: Path, module: str | None):
    """The family of a perfdb tree, `modules/<family>/perfdb`, loaded from the
    same modules tree."""
    from .registry import make_perf_desc
    root = Path(root).resolve()
    return make_perf_desc(module or root.parent.name, modules_dir=root.parent.parent)


def _cmd_show(args) -> int:
    path = Path(args.file)
    f = read_perfdb(path)
    root = path.resolve().parents[3]
    desc = _desc_for(root, args.module)
    entries = EntryList.load(root, desc.PROBLEM_COLUMNS, desc.SIZE_COLUMNS)
    writer = csv.writer(sys.stdout, lineterminator='\n')
    writer.writerow(('variant', 'entry') + entries.problem_columns + entries.size_columns + STAT_COLUMNS)
    for variant in sorted(f.blocks):
        for entry, line in sorted(f.blocks[variant].items()):
            problem, sizes = entries.rows_of(entry)
            values = (line,) * len(STAT_COLUMNS) if isinstance(line, str) else line
            writer.writerow((variant, entry) + problem + sizes + tuple(values))
    return 0


def _cmd_render(args) -> int:
    root = Path(args.perfdb)
    differ = render(root, _desc_for(root, args.module), check=args.check)
    if args.check and differ:
        for path in differ:
            print(f'out of date: {path}', file=sys.stderr)
        print('run: python -m aotriton.perfmon.perfdb render ' + str(root), file=sys.stderr)
        return 1
    for path in differ:
        print(f'wrote {path}')
    return 0


def _cmd_compare(args) -> int:
    root = Path(args.perfdb) if args.perfdb else None
    if root is None:
        from .registry import default_perfdb_dir
        root = default_perfdb_dir(args.module or 'flash')
    status = 0
    every = []
    arches = [args.arch] if args.arch else sorted(set(list_arches(root, args.tag_a))
                                                  & set(list_arches(root, args.tag_b)))
    for arch in arches:
        ratios, refused = compare_files(load_arch(root, args.tag_a, arch),
                                        load_arch(root, args.tag_b, arch),
                                        variant=args.variant)
        for name in refused:
            print(f'{arch}/{name}: refused, the measurement keys differ', file=sys.stderr)
            status = 1
        if not args.summary_only:
            print('arch,file,variant,entry,median_a,median_b,a/b')
            for name, v, entry, ma, mb, r in ratios:
                print(f'{arch},{name},{v},{entry},{fmt4(ma)},{fmt4(mb)},{fmt4(r)}')
        for name in sorted({r[0] for r in ratios}):
            g = geomean(r[5] for r in ratios if r[0] == name)
            print(f'# {arch} {name}: geometric mean a/b {_ratio_text(g)}')
        every += [(arch,) + r for r in ratios]
    print(f'# overall geometric mean a/b (above 1: {args.tag_b} is faster): '
          f'{_ratio_text(geomean(r[6] for r in every))} over {len(every)} lines')
    worst = sorted(every, key=lambda r: r[6])[:args.top]
    if worst:
        print(f'# largest regressions of {args.tag_b} against {args.tag_a}:')
        for arch, name, v, entry, ma, mb, r in worst:
            print(f'#   {arch} {name} {v} entry {entry}: {fmt4(ma)} -> {fmt4(mb)} us, a/b {fmt4(r)}')
    return status


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog='python -m aotriton.perfmon.perfdb',
                                     description='Read, render and compare a perfmon perfdb tree.')
    sub = parser.add_subparsers(dest='command', required=True)

    show = sub.add_parser('show', help='print a data file with its entries spelled out')
    show.add_argument('file')
    show.add_argument('--module',
                      default=None,
                      help='family (default: from the tree)')
    show.set_defaults(func=_cmd_show)

    rend = sub.add_parser('render', help='regenerate every README.md and <arch>.md')
    rend.add_argument('perfdb',
                      help='the perfdb directory, modules/<family>/perfdb')
    rend.add_argument('--check',
                      action='store_true',
                      help='write nothing; fail if any file is out of date')
    rend.add_argument('--module',
                      default=None,
                      help='family (default: from the tree)')
    rend.set_defaults(func=_cmd_render)

    comp = sub.add_parser('compare', help='compare two tags (A old, B new)')
    comp.add_argument('tag_a')
    comp.add_argument('tag_b')
    comp.add_argument('--arch', default=None)
    comp.add_argument('--variant', default=None)
    comp.add_argument('--perfdb',
                      default=None,
                      help='the perfdb directory (default: modules/<module>/perfdb)')
    comp.add_argument('--module',
                      default=None,
                      help='family (default: flash)')
    comp.add_argument('--top',
                      type=int,
                      default=10,
                      help='how many of the largest regressions to list')
    comp.add_argument('--summary_only',
                      action='store_true',
                      help='omit the per-line ratios')
    comp.set_defaults(func=_cmd_compare)
    return parser


def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else list(argv)
    # The shebang runs `python -m aotriton.perfmon.perfdb <file>`: show it.
    if argv and argv[0].endswith(EXT) and Path(argv[0]).is_file():
        argv = ['show'] + argv
    args = build_parser().parse_args(argv)
    return args.func(args)


if __name__ == '__main__':
    sys.exit(main())
