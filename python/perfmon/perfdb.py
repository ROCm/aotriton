"""
perfdb: perfmon's results in the repository, `modules/<family>/perfdb/`.
See docs/Human Readable Performance Database Format.md.

    modules/<family>/perfdb/
      README.md                            generated
      .metadata/problems.csv               problems; implicit ordinals, append-only
      .metadata/entries.csv                problem ordinal + sizes; implicit ordinals, append-only
      <tag>/README.md                      generated
      <tag>/<arch>.md                      generated
      <tag>/data/<arch>/<iface>.perfdb             the unforced operator
      <tag>/data/<arch>/<iface>.<backend>.perfdb   the operator forced to <backend>
      <tag>/data/<arch>/platform.csv       the machines that measured this arch

This module reads and writes that tree canonically (the same data always
gives the same bytes), merges new measurements into it, renders the markdown,
and compares two tags. It is also the parser named in the data files'
shebang:

    python -m aotriton.perfmon.perfdb show <file.perfdb>
    python -m aotriton.perfmon.perfdb render <perfdb dir> [--check]
    python -m aotriton.perfmon.perfdb compare <tag A> <tag B> [--arch A] [--variant V]

The lexical layer (shebang, comments, `#!` sections) is the tuning
database's, `aotriton.database.interpreter.read_sections`.
"""

import argparse
import csv
import io
import math
import re
import sys
from dataclasses import dataclass, field
from decimal import Decimal
from pathlib import Path

from aotriton.database.interpreter import read_sections

SHEBANG = '#!/usr/bin/env -S python -m aotriton.perfmon.perfdb'
EXT = '.perfdb'
METADATA_DIR = '.metadata'
PROBLEMS_CSV = 'problems.csv'
ENTRIES_CSV = 'entries.csv'
PLATFORM_CSV = 'platform.csv'
README = 'README.md'
DATA = 'data'

METADATA = 'metadata'
RESULTS = 'results'
STAT_COLUMNS = ('median', 'mean', 'stddev', 'min', 'p05', 'p95')
RESULTS_HEADER = ('entry',) + STAT_COLUMNS
#: `#! metadata` keys, in writing order. The last four say how the times were
#: taken; files that differ in any of them are never compared.
METADATA_KEYS = ('iface', 'backend', 'timing_method', 'iterations', 'l2_flush', 'unit')
MEASUREMENT_KEYS = ('timing_method', 'iterations', 'l2_flush', 'unit')
UNIT = 'us'

#: Line markers: measured without data (failed or crashed), and excluded (not
#: supported by the subject or arch, or does not fit the GPU).
NO_DATA = 'x'
EXCLUDED = '-'
#: `backend` of the unforced operator's file.
UNFORCED = '-'

#: Rendered forms of the markers.
SHOW_EXCLUDED = '—'
SHOW_NO_DATA = '✗'

PLATFORM_COLUMNS = ('variant', 'gpu_device_id', 'vram_gib', 'power_cap_w', 'power_cap_default_w',
                    'gpus_per_node', 'thermal_gate', 'cpu', 'ram_speed', 'os', 'kernel', 'amdgpu',
                    'rocm', 'harness', 'measured')

SUBJECT_RE = re.compile(r'^aotriton-(?P<tag>[^+/]+)\+rocm(?P<rocm>[^/]+)$')
BACKEND_RE = re.compile(r'^[a-z0-9_]+$')
GENERATED = '<!-- Generated by `python -m aotriton.perfmon.perfdb render`. Do not edit. -->'


class PerfdbError(ValueError):
    pass


# ---------------------------------------------------------------------------
# Numbers
# ---------------------------------------------------------------------------

def fmt4(x: float) -> str:
    """4 significant digits, no exponent, no trailing zeros: 12.3456 -> 12.35,
    123456 -> 123500, 0.081 -> 0.081."""
    x = float(x)
    if not math.isfinite(x):
        raise PerfdbError(f'not a finite number: {x!r}')
    if x == 0:
        return '0'
    text = format(Decimal(f'{x:.4g}'), 'f')
    if '.' in text:
        text = text.rstrip('0').rstrip('.')
    return '-' + text.lstrip('-') if x < 0 else text


def geomean(ratios) -> float | None:
    ratios = [r for r in ratios if r > 0]
    if not ratios:
        return None
    return math.exp(sum(math.log(r) for r in ratios) / len(ratios))


# ---------------------------------------------------------------------------
# Subjects and tags
# ---------------------------------------------------------------------------

def subject_tag(subject: str) -> tuple[str, str]:
    """('0.13b', '10.1.0') of 'aotriton-0.13b+rocm10.1.0'."""
    m = SUBJECT_RE.match(subject)
    if m is None:
        raise PerfdbError(f'subject {subject!r} is not aotriton-<tag>+rocm<version>')
    return m.group('tag'), m.group('rocm')


def tag_sort_key(tag: str):
    """Release order: by the numbers in the tag (0.9.2b < 0.10b < 0.11.2b)."""
    return tuple(int(n) for n in re.findall(r'\d+', tag)), tag


def list_tags(root: Path) -> list[str]:
    tags = [p.name for p in root.iterdir()
            if p.is_dir() and not p.name.startswith('.') and (p / DATA).is_dir()] if root.is_dir() else []
    return sorted(tags, key=tag_sort_key)


def list_arches(root: Path, tag: str) -> list[str]:
    data = root / tag / DATA
    return sorted(p.name for p in data.iterdir() if p.is_dir()) if data.is_dir() else []


def data_dir(root: Path, tag: str, arch: str) -> Path:
    return root / tag / DATA / arch


def variants_present(root: Path, tag: str, arch: str) -> set[str]:
    """The variants that have a `#! results` block in any data file of
    (tag, arch). Reads the section lines only, so it is cheap enough for
    listings."""
    out = set()
    d = data_dir(root, tag, arch)
    for path in sorted(d.glob(f'*{EXT}')) if d.is_dir() else []:
        with open(path, encoding='utf-8') as f:
            for line in f:
                if line.startswith(f'#! {RESULTS} '):
                    out.add(line.rstrip('\n')[len(f'#! {RESULTS} '):].strip())
    return out


# ---------------------------------------------------------------------------
# The entry list: .metadata/problems.csv + entries.csv
# ---------------------------------------------------------------------------

def _read_csv(path: Path) -> tuple[tuple[str, ...], list[tuple[str, ...]]]:
    with open(path, newline='', encoding='utf-8') as f:
        rows = [tuple(r) for r in csv.reader(f) if r]
    if not rows:
        raise PerfdbError(f'{path}: empty, not even a header')
    return rows[0], rows[1:]


def _csv_text(header, rows) -> str:
    out = io.StringIO()
    writer = csv.writer(out, lineterminator='\n')
    writer.writerow(header)
    writer.writerows(rows)
    return out.getvalue()


class EntryList:
    """problems.csv and entries.csv, with HRDB's implicit ordinals (the first
    data row is 1). Rows are found by content and only ever appended."""

    def __init__(self, problem_columns, size_columns):
        self.problem_columns = tuple(problem_columns)
        self.size_columns = tuple(size_columns)
        self.problems: list[tuple[str, ...]] = []
        self.entries: list[tuple[str, ...]] = []      # (problem ordinal, *sizes), as text
        self._problem_index: dict[tuple, int] = {}
        self._entry_index: dict[tuple, int] = {}
        self.appended = {'problems': 0, 'entries': 0}

    @property
    def entries_header(self) -> tuple[str, ...]:
        return ('problem',) + self.size_columns

    @classmethod
    def load(cls, root: Path, problem_columns, size_columns) -> 'EntryList':
        out = cls(problem_columns, size_columns)
        meta = root / METADATA_DIR
        if (meta / PROBLEMS_CSV).is_file():
            header, rows = _read_csv(meta / PROBLEMS_CSV)
            if header != out.problem_columns:
                raise PerfdbError(f'{meta / PROBLEMS_CSV}: columns {header} differ from the '
                                  f'family\'s {out.problem_columns}; a new column needs a migration')
            for row in rows:
                out._add_problem(row)
        if (meta / ENTRIES_CSV).is_file():
            header, rows = _read_csv(meta / ENTRIES_CSV)
            if header != out.entries_header:
                raise PerfdbError(f'{meta / ENTRIES_CSV}: columns {header}, expected {out.entries_header}')
            for row in rows:
                if not 1 <= int(row[0]) <= len(out.problems):
                    raise PerfdbError(f'{meta / ENTRIES_CSV}: problem ordinal {row[0]} out of range')
                out._add_entry(row)
        out.appended = {'problems': 0, 'entries': 0}
        return out

    def _add_problem(self, row) -> int:
        row = tuple(row)
        if len(row) != len(self.problem_columns):
            raise PerfdbError(f'problem row {row} does not have {len(self.problem_columns)} cells')
        if row in self._problem_index:
            raise PerfdbError(f'problem {row} is listed twice')
        self.problems.append(row)
        self._problem_index[row] = len(self.problems)
        self.appended['problems'] += 1
        return len(self.problems)

    def _add_entry(self, row) -> int:
        row = tuple(row)
        if len(row) != len(self.entries_header):
            raise PerfdbError(f'entry row {row} does not have {len(self.entries_header)} cells')
        if row in self._entry_index:
            raise PerfdbError(f'entry {row} is listed twice')
        self.entries.append(row)
        self._entry_index[row] = len(self.entries)
        self.appended['entries'] += 1
        return len(self.entries)

    def problem_ordinal(self, problem_row, *, add: bool = False) -> int | None:
        found = self._problem_index.get(tuple(problem_row))
        if found is None and add:
            found = self._add_problem(problem_row)
        return found

    def entry_ordinal(self, problem_row, size_row, *, add: bool = False) -> int | None:
        problem = self.problem_ordinal(problem_row, add=add)
        if problem is None:
            return None
        row = (str(problem),) + tuple(size_row)
        found = self._entry_index.get(row)
        if found is None and add:
            found = self._add_entry(row)
        return found

    def rows_of(self, ordinal: int) -> tuple[tuple[str, ...], tuple[str, ...]]:
        """(problem row, size row) of entry `ordinal`."""
        row = self.entries[ordinal - 1]
        return self.problems[int(row[0]) - 1], row[1:]

    def ordinal_of(self, desc, entry, *, add: bool = False) -> int | None:
        return self.entry_ordinal(desc.problem_row(entry), desc.size_row(entry), add=add)

    def entry_of(self, desc, ordinal: int):
        return desc.entry_from_rows(*self.rows_of(ordinal))

    def save(self, root: Path) -> None:
        meta = root / METADATA_DIR
        meta.mkdir(parents=True, exist_ok=True)
        write_if_changed(meta / PROBLEMS_CSV, _csv_text(self.problem_columns, self.problems))
        write_if_changed(meta / ENTRIES_CSV, _csv_text(self.entries_header, self.entries))


def write_if_changed(path: Path, text: str) -> bool:
    if path.is_file() and path.read_text(encoding='utf-8') == text:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding='utf-8')
    return True


